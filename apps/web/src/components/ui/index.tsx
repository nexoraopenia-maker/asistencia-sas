// --- Skeleton ---------------------------------------------------------------

/**
 * Esqueleto con brillo en movimiento.
 *
 * El `animate-pulse` de Tailwind solo cambia la opacidad; el barrido de luz
 * comunica mejor "esto esta cargando" que un bloque que parpadea, y evita que
 * se confunda con un elemento deshabilitado.
 */
export function Skeleton({ className, ...props }: React.HTMLAttributes<HTMLDivElement>) {
  return (
    <div
      className={cn("relative overflow-hidden rounded-xl bg-secondary", className)}
      {...props}
    >
      <div className="absolute inset-0 -translate-x-full animate-shimmer bg-gradient-to-r from-transparent via-foreground/10 to-transparent" />
    </div>
  );
}

